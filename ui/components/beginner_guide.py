# ===== 各概念的正文（Markdown）=====

_KLINE = """一根K线（蜡烛）= 把一天（或一周/一月）的价格压缩成一张图：
**开盘价、收盘价、最高价、最低价**。

- 收盘 > 开盘 → **红色**（涨）；收盘 < 开盘 → **绿色**（跌）。中国约定红涨绿跌，和美股相反，别搞反
- 中间的"实体"是开盘到收盘的范围；上下两根细线（影线）是当天碰到过的最高/最低价

**例子**：茅台某天开盘 1300 元、收盘 1310 元、最高 1315、最低 1295
→ 一根红色蜡烛：实体从 1300 到 1310，上面影线伸到 1315，下面影线垂到 1295。
说明当天虽然收涨，但盘中一度跌到 1295（有人恐慌过）。"""

_MA = """**均线 MA = 最近 N 天收盘价的平均值**连成的线，可以理解成
「最近 N 天里买入的人的**平均成本**」。

**例子**：最近 5 天收盘价是 100、101、102、103、104 元
→ MA5 = (100+101+102+103+104) ÷ 5 = **102 元**。现价 104 在 MA5 上方，
说明最近 5 天买入的人平均是赚的。

**怎么看**：短期均线（MA5）在长期均线（MA20）上方 → 「多头排列」，趋势偏强；
反过来压在下面 → 「空头排列」，趋势偏弱。均线粘在一起横着走 → 要选方向了。"""

_MACD = """MACD 衡量的是**上涨/下跌的"劲儿"在变强还是变弱**，由快线 DIF、慢线 DEA
和柱子组成。DIF 上穿 DEA 叫**金叉**（动能转强的信号），下穿叫**死叉**。

**例子**：把它想成两辆车——快车（短期均价）和慢车（长期均价）。
快车刚起步加速时，两车距离越拉越大（柱子变长）＝劲儿在增强；
距离开始缩小，哪怕快车仍然在前面，也提示「劲儿可能在用完」。

**注意**：金叉死叉只是概率信号，震荡市里会频繁出错（本项目回测证实了这一点）。"""

_RSI = """RSI 衡量「最近涨（跌）的劲头是否过头」，范围 0~100。
**> 70 超买**（涨太急，短期可能回调），**< 30 超卖**（跌太狠，可能反弹）。

**例子**：像体温计——RSI 78 ≈ 发烧 39 度：不一定马上进医院，
但肯定不正常，该留神了。RSI 45 ≈ 36.5 度，一切正常。

**怎么看**：本 app 画了 RSI6（短线）/14/24（长线）三条，看它当前在哪条参考线附近。"""

_BOLL = """布林带 = 用过去 20 天的波动幅度，算出股价的「**正常活动范围**」：
中轨是 20 日均价，上下轨各往外扩 2 个标准差。

**例子**：皮筋——拉得太开（碰到上轨）会往回弹，压得太紧（碰到下轨）会往上弹；
**带宽收得极窄**（上中下三轨挤在一起）＝憋着一股劲，往往不久后突然选方向。

**注意**：强趋势里价格可以「贴着上轨走」很久，碰上轨≠马上跌。"""

_VOL = """成交量 = 当天一共成交了多少钱，代表**市场关注度**。量比 > 1.5 说明比平时活跃。

**例子**：一家奶茶店今天排队（放量）→ 涨价大家也认；没人排队却宣布涨价（缩量）→
多半撑不住。股价也一样：**涨 + 放量**＝追的人多、涨得"实"；
**涨 + 缩量**＝没人跟、涨得"虚"；**跌 + 放量**＝恐慌出逃，最危险。"""

_SUPPORT = """**支撑位**＝历史上多次跌到就弹起来的价格（地板）；**压力位**＝多次涨到就被
打回去的价格（天花板）。它们不是精确数字，是一段区域。

**例子**：一只股票三次跌到 95 元附近都被买回来 → 95 元是支撑位；
两次冲到 110 元都失败回落 → 110 元是压力位。突破天花板后，天花板常变成新地板。"""

_NEWS = """新闻情绪分析会把每条消息标成**利好 / 利空 / 中性**：

- **利好**：可能让股价涨的消息——业绩超预期、拿下大订单、公司回购自家股票
- **利空**：可能让它跌的消息——业绩暴雷、大股东减持、被立案调查
- **中性**：短期看不出影响——例行董事会、常规人事变动

**例子**：「公司公告获得 50 亿元大订单」→ 利好；
「控股股东拟减持不超过 2%」→ 利空（大股东卖出，通常被解读为不看好）；
「将于下月召开股东大会」→ 中性。

**提醒**：利好落地也可能变利空——涨预期涨了半年，消息一兑现反而有人砸盘。
消息要结合股价当前的位置看，不能只看标签。"""

_PE = """**PE（市盈率）＝ 股价 ÷ 每股年利润**，可以读成「**花多少钱买 1 元的年利润**」，
或「按现在的盈利水平，几年回本」。

**例子**：PE 25 ＝ 花 25 元买 1 元的年利润。一家奶茶店年赚 10 万、你花 250 万盘下它
→ PE 25。

**怎么看**：
- 不同行业 PE 天差地别：银行股常只有 5~6，高成长科技股可能 40+。**只能和同行业比，不能跨行业比**
- PE 为负 ＝ 公司在亏损，这个数没意义
- PE 高不一定是"贵"：市场可能预期它利润会快速增长（分母以后会变大）"""

_PB = """**PB（市净率）＝ 股价 ÷ 每股净资产**，可以读成「**1 块钱的家产卖多少钱**」。

**例子**：PB 8 ＝ 花 8 元买 1 元净资产。听起来贵？茅台的家产（厂房、存货）不多，
但靠品牌一年赚几百亿——**靠资产赚不了钱的公司，看 PB 会严重低估它**；
反过来，银行、钢铁这类重资产行业，看 PB 比看 PE 更实在（银行 PB 常 < 1，即半价卖家产）。"""

_ROE = """**ROE（净资产收益率）＝ 净利润 ÷ 净资产**，衡量「用它家产**一年能赚回几个百分点**」。

**例子**：你开小店投了 100 万，一年净赚 20 万 → ROE 20%。长期 ROE > 15% 的公司，
通常被视作「赚钱能力强」——这是巴菲特最看重的单一指标。"""

_MARGIN = """**毛利率**＝卖货的赚头；**净利率**＝扣完所有成本后最后剩的；**营收增速**＝生意在扩张还是收缩。

**例子**：一杯奶茶卖 20 元：原料杯子共 6 元 → 毛利率 70%；
再扣房租、人工、广告后剩 2 元 → 净利率 10%。
去年卖了 100 杯今年卖 130 杯 → 营收增速 +30%。毛利率高说明产品有定价权（茅台毛利率 > 90%）。"""

_PRED = """本 app 的最终判断是「**看涨 / 看跌 / 震荡**」+ 一个**置信度**百分比。

**例子**：置信度 60% 的「看涨」＝模型有六成把握，它自己也在告诉你**四成可能错**。
哪怕是 85% 的看涨，也完全可能下跌——**预测是概率，不是保证**。

**所以才有「🏆 战绩」页**：每次预测都会存档，预测期走完后自动和实际走势对照。
用战绩验证这个工具到底准不准，比听它说得头头是道重要得多。"""

_GAP = """报告头部的「**数据缺口提示**」＝ 这次分析缺了哪路数据（比如新闻情绪分析失败）。

**例子**：体检报告上写「该项未检测」——你不会把它读成「这项一切正常」。
同样，报告说「公告检索失败，未包含公告动态」意思是「**这次没看到公告**」，
而不是「公司没有公告」。缺口存在时置信度也会被强制下调（封顶 0.6），这是代码兜的底。"""


def _financial_live_lines(financial_data: Optional[Dict]) -> str:
    """把当前股票的真实 PE/PB/ROE 拼成一条「活例子」，没数据就返回空串"""
    if not financial_data:
        return ""
    parts = []
    pe = financial_data.get("pe")
    pb = financial_data.get("pb")
    roe = financial_data.get("roe")
    if pe:
        parts.append(f"PE={pe:.1f}，相当于花 {pe:.1f} 元买它 1 元的年利润")
    if pb:
        parts.append(f"PB={pb:.1f}，即 1 元家产卖 {pb:.1f} 元")
    if roe:
        parts.append(f"ROE={roe:.1f}%，家产一年能赚回 {roe:.1f}%")
    if not parts:
        return ""
    return "\n\n> 🎯 **拿你正在看的这只股票当例子**：" + "；".join(parts) + "。"


def render_beginner_guide(
    financial_data: Optional[Dict] = None,
) -> None:
    """「📖 新手科普」tab：术语扫盲，财务三件套注入当前股票的真实数值当例子"""
    st.markdown(
        "第一次看盘？按顺序点开下面每个概念，每个只要 30 秒："
        "**一句话定义 → 具体数字例子 → 在本 app 里怎么看**。"
    )
    live = _financial_live_lines(financial_data)

    def _show(fig):
        """科普配图：紧凑、隐藏工具栏，点开即看"""
        from ui.chart_theme import apply_dark
        st.plotly_chart(apply_dark(fig), use_container_width=True,
                        config={"displayModeBar": False})

    from ui.components.guide_figures import (
        fig_candle, fig_ma, fig_macd, fig_rsi,
        fig_boll, fig_support, fig_pe_compare, fig_margin,
    )

    with st.expander("🕯️ K线：一根蜡烛看懂一天的行情", expanded=True):
        st.markdown(_KLINE)
        _show(fig_candle())
    with st.expander("📈 均线（MA5/MA20/MA60）：大家的平均成本"):
        st.markdown(_MA)
        _show(fig_ma())
    with st.expander("⚡ MACD：上涨的劲儿还在不在"):
        st.markdown(_MACD)
        _show(fig_macd())
    with st.expander("🌡️ RSI：市场体温计（70 过热 / 30 过冷）"):
        st.markdown(_RSI)
        _show(fig_rsi())
    with st.expander("🎈 布林带：正常波动范围"):
        st.markdown(_BOLL)
        _show(fig_boll())
    with st.expander("📊 成交量与量比：人气有多旺"):
        st.markdown(_VOL)
    with st.expander("🧱 支撑位与压力位：地板和天花板"):
        st.markdown(_SUPPORT)
        _show(fig_support())
    with st.expander("📰 利好 / 利空 / 中性：消息怎么读"):
        st.markdown(_NEWS)

    with st.expander("💰 PE（市盈率）：花几块钱买 1 元利润"):
        st.markdown(_PE + live)
        _show(fig_pe_compare())
    with st.expander("🏦 PB（市净率）：1 块家产卖几块钱"):
        st.markdown(_PB + live)
    with st.expander("🏆 ROE（净资产收益率）：赚钱效率"):
        st.markdown(_ROE + live)
    with st.expander("🧋 毛利率 / 净利率 / 营收增速：一门生意的三本账"):
        st.markdown(_MARGIN)
        _show(fig_margin())
    with st.expander("🎲 看涨/看跌/震荡 + 置信度：怎么读最终结论"):
        st.markdown(_PRED)
    with st.expander("⚠️ 数据缺口提示：为什么报告里有些数据'缺失'"):
        st.markdown(_GAP)

    st.markdown("---")
    st.caption(
        "本页是通用科普，不构成投资建议。所有概念都只是概率信号——"
        "本项目用回测和战绩页专门验证过它们到底准不准，结论在 README 里。"
    )
